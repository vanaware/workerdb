/// <reference lib="deno.ns" />
import "fake-indexeddb/auto";
import { assert, assertEquals, assertNotEquals, } from "@std/assert";
import {
  generateId,
  generateIdFallback,
  validateId,
} from "../src/utils/id.ts";

Deno.test("generateId - must produce a string ID with an appropriate length", () => {
  const id = generateId();
  assert(typeof id === "string", "The generated ID must be a string",);
  assert(
    id.length > 0 && id.length <= 24,
    "The ID length must be between 1 and 24 characters",
  );
});

Deno.test("generateId - must not produce duplicate IDs on sequential calls", () => {
  const id1 = generateId();
  const id2 = generateId();
  assertNotEquals(
    id1,
    id2,
    "Sequentially generated IDs must not be identical",
  );
});

Deno.test("generateIdFallback - must work as a safe alternative", () => {
  const idFallback = generateIdFallback();
  assert(
    typeof idFallback === "string",
    "The fallback ID must be a string",
  );
  assert(idFallback.length > 0, "The fallback ID must not be empty",);
});

Deno.test("validateId - must validate length boundaries correctly", () => {
  const validId = generateId();
  const tooLongId = "a".repeat(25,);
  const emptyId = "";
  assertEquals(
    validateId(validId,),
    true,
    "Must accept an ID generated by the function itself",
  );
  assertEquals(
    validateId(tooLongId,),
    false,
    "Must not accept IDs longer than 24 characters",
  );
  assertEquals(
    validateId(emptyId,),
    false,
    "Must not accept empty IDs",
  );
});
